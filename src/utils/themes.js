// Apply theme to CSS custom properties
export function applyTheme(themeName) {
  const theme = colorThemes[themeName]
  if (!theme) return

  const root = document.documentElement
  root.style.setProperty('--primary-color', theme.primary)
  root.style.setProperty('--primary-dark', theme.primaryDark)
  root.style.setProperty('--primary-light', theme.primaryLight)
  root.style.setProperty('--secondary-color', theme.secondary)
  root.style.setProperty('--accent-color', theme.accent)
  root.style.setProperty('--accent-dark', theme.accentDark)
  root.style.setProperty('--bg-primary', theme.bgPrimary)
  root.style.setProperty('--bg-secondary', theme.bgSecondary)
  root.style.setProperty('--bg-tertiary', theme.bgTertiary)
  root.style.setProperty('--bg-card', theme.bgCard)
  root.style.setProperty('--text-primary', theme.textPrimary)
  root.style.setProperty('--text-secondary', theme.textSecondary)
  root.style.setProperty('--text-light', theme.textLight)
  root.style.setProperty('--text-white', theme.textWhite)
  root.style.setProperty('--border-light', theme.borderLight)
  root.style.setProperty('--border-focus', theme.primary)
  root.style.setProperty('--shadow', theme.shadow)
  root.style.setProperty('--shadow-hover', theme.shadowHover)
}